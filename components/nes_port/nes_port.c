/* RGB565 conversion of the nofrendo 256 entry RGB palette. */
static void video_set_palette(rgb_t *pal)
{
    if (pal == NULL) {
        return;
    }

    for (int i = 0; i < NES_PALETTE_SIZE; i++) {
        uint16_t r = (uint16_t) (pal[i].r & 0xF8);
        uint16_t g = (uint16_t) (pal[i].g & 0xFC);
        uint16_t b = (uint16_t) (pal[i].b & 0xF8);
        s_palette[i] = (uint16_t) ((r << 8) | (g << 3) | (b >> 3));
    }

    palette_refresh_luminance();
}

