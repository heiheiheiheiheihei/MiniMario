uint32_t nes_port_fb_checksum(void)
{
    const uint8_t *p = fb_visible();
    uint32_t hash = 2166136261u;
    for (int i = 0; i < NES_VIS_H * NES_FB_W; i++) {
        hash ^= p[i];
        hash *= 16777619u;
    }
    return hash;
}

