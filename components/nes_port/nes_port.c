esp_err_t nes_port_init(void)
{
    if (s_initialized) {
        return ESP_OK;
    }

    /* Rendering target: static .bss buffer, handed to the video layer. */
    vid_setstaticbuffer(s_fb, NES_FB_W, NES_FB_H);

    if (vid_init(NES_FB_W, NES_FB_H, &s_driver) != 0) {
        return ESP_FAIL;
    }

    event_init();
    event_set_system(system_nes); /* joypad events -> nesinput */
    gui_init();

    palette_refresh_luminance();
    stats_reset();
    s_initialized = true;
    return ESP_OK;
}

esp_err_t nes_port_set_rom(const uint8_t *rom, size_t len)
{
    if (rom == NULL) {
        return ESP_ERR_INVALID_ARG;
    }
    if (s_running) {
        return ESP_ERR_INVALID_STATE;
    }
    if (len < 16 || memcmp(rom, "NES\x1a", 4) != 0) {
        ESP_LOGW(TAG, "not an iNES image");
        return ESP_ERR_INVALID_ARG;
    }

    uint8_t prg_banks = rom[4];
    uint8_t chr_banks = rom[5];
    uint8_t flags6 = rom[6];
    uint8_t flags7 = rom[7];
    uint32_t mapper = (uint32_t) ((flags6 >> 4) | (flags7 & 0xF0));

    size_t needed = 16;
    if (flags6 & 0x04) {
        needed += 512; /* trainer */
    }
    needed += (size_t) prg_banks * 16384u + (size_t) chr_banks * 8192u;
    if (len < needed) {
        ESP_LOGW(TAG, "truncated ROM: have %u need %u", (unsigned) len,
                 (unsigned) needed);
        return ESP_ERR_INVALID_SIZE;
    }
    if (!mmc_peek((int) mapper)) {
        ESP_LOGW(TAG, "mapper %u not supported", (unsigned) mapper);
        return ESP_ERR_NOT_SUPPORTED;
    }

    s_rom = rom;
    s_rom_len = len;
    s_rom_mapper = mapper;
    return ESP_OK;
}

