static void stats_reset(void)
{
    s_frames = s_drawn = s_skipped = 0;
    s_fps_x100 = 0;
    s_last_frame_us = s_last_core_us = s_last_sink_us = 0;
    s_max_frame_us = s_total_frame_us = s_total_core_us = s_total_sink_us = 0;
    s_win_frames = 0;
    s_win_start = esp_timer_get_time();
}

static void palette_refresh_luminance(void)
{
    for (int i = 0; i < NES_PALETTE_SIZE; i++) {
        uint16_t c = s_palette[i];
        int r = (c >> 11) & 0x1F;
        int g = (c >> 5) & 0x3F;
        int b = c & 0x1F;
        /* 0..255, cheap approximation of perceptual luminance */
        int l = (r * 8 * 299 + g * 4 * 587 + b * 8 * 114) / 1000;
        if (l > 255) l = 255;
        if (l < 0) l = 0;
        s_lum[i] = (uint8_t) l;
    }
}

/* The visible picture: skip the 8 line top overscan. */
static inline const uint8_t *fb_visible(void)
{
    return s_fb + (NES_VIS_Y * NES_FB_W);
}

