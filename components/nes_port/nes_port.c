esp_err_t nes_port_run(void)
{
    if (!s_initialized) {
        ESP_LOGE(TAG, "nes_port_init() not called");
        return ESP_ERR_INVALID_STATE;
    }
    if (s_rom == NULL) {
        ESP_LOGE(TAG, "no ROM set");
        return ESP_ERR_INVALID_STATE;
    }
    if (s_running) {
        return ESP_ERR_INVALID_STATE;
    }

    int64_t heap_before = esp_get_free_heap_size();
    ESP_LOGI(TAG, "run: rom=%s len=%u mapper=%u heap_before=%d",
             s_rom_name, (unsigned) s_rom_len, (unsigned) s_rom_mapper,
             (int) heap_before);

    if (vid_setmode(NES_FB_W, NES_FB_H) != 0) {
        ESP_LOGE(TAG, "vid_setmode failed");
        return ESP_FAIL;
    }

    nes_t *nes = nes_create();
    if (nes == NULL) {
        ESP_LOGE(TAG, "nes_create failed");
        return ESP_FAIL;
    }
    s_nes = nes;

    int cart_err = nes_insertcart(s_rom_name, nes);
    if (cart_err != 0 || nes->rominfo == NULL) {
        ESP_LOGE(TAG, "nes_insertcart failed (%d)", cart_err);
        nes_poweroff();
        nes_destroy(&s_nes);
        s_nes = NULL;
        return ESP_FAIL;
    }

    s_rom_mapper = (uint32_t) nes->rominfo->mapper_number;
    s_heap_free = (uint32_t) esp_get_free_heap_size();
    ESP_LOGI(TAG, "cart ok: %s", rom_getinfo(nes->rominfo));
    ESP_LOGI(TAG, "heap_after_load=%u (used by emu=%d) prg=%dk chr=%dk mapper=%u",
             (unsigned) s_heap_free, (int) (heap_before - esp_get_free_heap_size()),
             (int) (nes->rominfo->rom_banks * 16),
             (int) (nes->rominfo->vrom_banks * 8),
             (unsigned) s_rom_mapper);

    /* ------------------------------------------------------------------ */
    /* Frame loop: exactly one emulated NTSC frame per 16639 us.           */
    /* ------------------------------------------------------------------ */
    stats_reset();
    s_quit_request = false;
    s_paused = false;
    s_running = true;

    bool draw = true;
    int64_t next_frame = esp_timer_get_time();
    int64_t deadline = next_frame;
    int32_t frac = 0;
    int64_t budget = FRAME_PERIOD_US; /* token bucket, decides frame skip */
    int64_t draw_extra = FRAME_PERIOD_US / 2;
    uint32_t last_draw_cost = 0;
    uint32_t last_skip_cost = 0;
    bool have_draw_cost = false;
    bool have_skip_cost = false;
    int64_t last_draw_time = next_frame;
    int64_t last_log_time = next_frame;

    while (!s_quit_request) {
        if (s_paused) {
            /* Keep the frame cadence (and quit responsiveness) but do not
             * advance the console, so the framebuffer stays stable. */
            deadline += FRAME_PERIOD_US;
            frac += 333;
            if (frac >= 1000) {
                frac -= 1000;
                deadline += 1;
            }
            int64_t tp = esp_timer_get_time();
            if (tp < deadline) {
                vTaskDelay((TickType_t) ((deadline - tp + 999) / 1000));
            } else if (tp - deadline > (int64_t) 4 * FRAME_PERIOD_US) {
                deadline = tp;
            }
            continue;
        }

        int64_t t0 = esp_timer_get_time();
        s_frame_sink_us = 0;

        if (draw) {
            nes_emulate_frame(true);
        } else {
            nes_emulate_frame(false);
        }

        int64_t t1 = esp_timer_get_time();
        uint32_t cost = (uint32_t) (t1 - t0);

        s_frames++;
        s_win_frames++;
        s_last_frame_us = cost;
        s_last_sink_us = s_frame_sink_us;
        s_last_core_us = (cost > s_frame_sink_us) ? cost - s_frame_sink_us : 0;
        s_total_frame_us += cost;
        s_total_core_us += s_last_core_us;
        s_total_sink_us += s_last_sink_us;
        if (cost > s_max_frame_us) {
            s_max_frame_us = cost;
        }

        if (draw) {
            s_drawn++;
            last_draw_cost = cost;
            have_draw_cost = true;
            last_draw_time = t1;
        } else {
            s_skipped++;
            last_skip_cost = cost;
            have_skip_cost = true;
        }

        /* Rolling fps over a ~2 s window (emulated frames, not displayed). */
        if (t1 - s_win_start >= 2000000) {
            int64_t span = t1 - s_win_start;
            if (span > 0) {
                s_fps_x100 = (uint32_t) (((int64_t) s_win_frames * 100000000) / span);
            }
            s_win_start = t1;
            s_win_frames = 0;
        }

        if (s_debug_log && (t1 - last_log_time) >= 1000000) {
            last_log_time = t1;
            s_heap_free = (uint32_t) esp_get_free_heap_size();
            debug_log_frame(t1);
        }

        /* Token bucket: every frame earns 16.6ms of emulated time, a drawn
         * frame costs an extra "render" amount compared to a skipped one.
         * When the display is slow this naturally produces a display rate
         * below 60Hz without ever slowing the emulated console down. */
        budget += (int64_t) FRAME_PERIOD_US - (int64_t) cost;
        if (budget > (int64_t) 3 * FRAME_PERIOD_US) {
            budget = (int64_t) 3 * FRAME_PERIOD_US;
        } else if (budget < (int64_t) -2 * FRAME_PERIOD_US) {
            budget = (int64_t) -2 * FRAME_PERIOD_US;
        }

        if (have_draw_cost && have_skip_cost) {
            draw_extra = (last_draw_cost > last_skip_cost)
                             ? (int64_t) (last_draw_cost - last_skip_cost)
                             : 0;
        }

        draw = (budget >= draw_extra - 500);
        if (!draw && (t1 - last_draw_time) > 500000) {
            draw = true; /* keep at least a couple of visible frames per second */
        }

        /* Absolute deadline pacing. */
        next_frame = deadline + FRAME_PERIOD_US;
        frac += 333;
        if (frac >= 1000) {
            frac -= 1000;
            next_frame += 1;
        }
        deadline = next_frame;

        int64_t t2 = esp_timer_get_time();
        if (t2 < deadline) {
            int64_t sleep_us = deadline - t2;
            /* Sleep in whole freeRTOS ticks; oversleeping less than one tick
             * does not accumulate because the deadline is absolute. */
            vTaskDelay((TickType_t) ((sleep_us + 999) / 1000));
        } else if (t2 - deadline > (int64_t) 4 * FRAME_PERIOD_US) {
            /* Far behind (e.g. display stall): resync, do not spin. */
            deadline = t2;
        }
    }

    /* ------------------------------------------------------------------ */
    /* Clean shutdown so another ROM can be loaded in the same boot.       */
    /* ------------------------------------------------------------------ */
    s_running = false;
    uint32_t frames = s_frames;
    uint32_t drawn = s_drawn;
    uint32_t skipped = s_skipped;
    uint32_t fps = s_fps_x100;
    uint32_t chk = nes_port_fb_checksum();

    nes_poweroff();
    nes_destroy(&s_nes);
    s_nes = NULL;
    s_heap_free = (uint32_t) esp_get_free_heap_size();

    ESP_LOGI(TAG, "run end: frames=%u drawn=%u skipped=%u fps=%u.%02u "
             "heap=%u chk=%08x",
             (unsigned) frames, (unsigned) drawn, (unsigned) skipped,
             (unsigned) (fps / 100), (unsigned) (fps % 100),
             (unsigned) s_heap_free, (unsigned) chk);

    return ESP_OK;
}
