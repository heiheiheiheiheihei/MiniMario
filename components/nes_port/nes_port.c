/* Called through the video driver's custom_blit hook from vid_flush() at the
 * end of every rendered frame.  The PPU already wrote into s_fb. */
static void osd_custom_blit(bitmap_t *primary, int num_dirties, rect_t *dirty_rects)
{
    (void) num_dirties;
    (void) dirty_rects;

    int64_t t0 = esp_timer_get_time();

    if (s_sink != NULL) {
        const uint8_t *vis = primary->data + (NES_VIS_Y * primary->pitch);
        s_sink(vis, s_palette);
    }

    s_frame_sink_us = (uint32_t) (esp_timer_get_time() - t0);
}

