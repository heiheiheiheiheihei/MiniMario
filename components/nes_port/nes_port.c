/* 80x25 ASCII art of the visible framebuffer, for eyeballing over serial. */
int nes_port_debug_ascii(char *out, size_t len)
{
    const uint8_t *fb = fb_visible();
    char line[ASCII_COLS + 1];
    int pos = 0;

    for (int row = 0; row < ASCII_ROWS; row++) {
        int y0 = row * NES_VIS_H / ASCII_ROWS;
        int y1 = (row + 1) * NES_VIS_H / ASCII_ROWS;
        if (y1 <= y0) y1 = y0 + 1;

        for (int col = 0; col < ASCII_COLS; col++) {
            int x0 = col * NES_FB_W / ASCII_COLS;
            int x1 = (col + 1) * NES_FB_W / ASCII_COLS;
            if (x1 <= x0) x1 = x0 + 1;

            uint32_t sum = 0;
            uint32_t count = 0;
            for (int y = y0; y < y1; y++) {
                const uint8_t *p = fb + y * NES_FB_W;
                for (int x = x0; x < x1; x++) {
                    sum += s_lum[p[x]];
                    count++;
                }
            }
            int lum = count ? (int) (sum / count) : 0;
            int idx = (lum * ASCII_RAMP_LEN) / 256;
            if (idx >= ASCII_RAMP_LEN) idx = ASCII_RAMP_LEN - 1;
            line[col] = ASCII_RAMP[idx];
        }
        line[ASCII_COLS] = '\0';

        if (out != NULL && pos + ASCII_COLS + 1 < (int) len) {
            memcpy(out + pos, line, ASCII_COLS);
        }
        pos += ASCII_COLS;
        if (out != NULL && pos + 1 < (int) len) {
            out[pos] = '\n';
        }
        pos += 1;
    }

    if (out != NULL && (size_t) pos < len) {
        out[pos] = '\0';
    }
    return pos;
}

