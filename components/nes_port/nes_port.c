/* Joypad: call the app's input source once per emulated frame and turn the
 * NES_PAD_* mask into nofrendo joypad events. */
void osd_getinput(void)
{
    static const int event_map[8] = {
        event_joypad1_a,     event_joypad1_b,    event_joypad1_select,
        event_joypad1_start, event_joypad1_up,   event_joypad1_down,
        event_joypad1_left,  event_joypad1_right,
    };
    static uint8_t prev_buttons = 0;

    uint8_t buttons = (s_input_src != NULL) ? s_input_src() : 0;
    uint8_t changed = (uint8_t) (buttons ^ prev_buttons);
    prev_buttons = buttons;

    for (int bit = 0; bit < 8; bit++) {
        if ((changed & (1u << bit)) == 0) {
            continue;
        }
        event_t handler = event_get(event_map[bit]);
        if (handler != NULL) {
            handler((buttons & (1u << bit)) ? INP_STATE_MAKE : INP_STATE_BREAK);
        }
    }
}

