/*
 * MiniMario - nofrendo NES core port / OSD layer for the ESP32-C6.
 *
 * This file implements the frozen API from include/nes_port.h on top of the
 * nofrendo core in components/nofrendo.  It replaces the old IDF v3
 * components/nofrendo-esp32 OSD (raw SPI register poking, dual core video
 * queue, DAC audio) with:
 *
 *   - a static 256x240 palette index framebuffer that the nofrendo PPU renders
 *     into directly (no extra 57KB blit buffer, no heap allocation),
 *   - a 256 entry RGB565 palette converted in the video driver set_palette hook,
 *   - an own frame loop paced by esp_timer at 60.0988 Hz (16639 us/frame),
 *     with token-bucket frame skipping so a slow display can never slow the
 *     emulated console down,
 *   - no audio at all (the board has no speaker/DAC); the APU frame IRQ is
 *     still generated by nes.c's per-scanline fiq check, only the audio sample
 *     generation callback is never installed.
 *
 * GPLv2, as it is a derived work of nofrendo (c) 1998-2000 Matthew Conte.
 */

